#!/usr/bin/env node
// Generates ccar-f/ccar-p.mock-papers-layout.js: six fixed 63-question CCAR-P practice papers.
// Run from the repository root:  node ccar-f/tools/build-ccar-p-papers.js
// Every pool item is used exactly once. Each paper matches the exam's domain weights and item-type
// mix, contains exactly one yes/no grid, covers every exam-guide objective, and never repeats a
// concept family. Re-running with the same inputs produces the same layout.
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..");
const { loadCcarpPapers, SIM_OBJECTIVES } = require("./ccar-p-papers-load.js");

const LAYOUT_VERSION = "2026-11-06-layout-v1";
const PAPER_COUNT = 6;
// Per-paper item types by internal domain: [single, multi, composite]. Matches the 44/14/5 mix of
// the existing 63-item exam simulation (audits/ccar-p-exam-fidelity.json).
const TYPE_SPLIT = { P1: [8, 3, 1], P2: [8, 2, 1], P3: [7, 2, 1], P4: [6, 2, 1], P5: [6, 2, 1], P6: [6, 2, 0], P7: [3, 1, 0] };

function main() {
  const { window, objectivesByDomain, builder } = loadCcarpPapers(ROOT);
  const profile = window.CLAUDE_CERTIFICATIONS["ccar-p"];
  const { items } = builder.buildPool();
  const fail = (m) => { throw new Error(m); };

  // Objectives for reused items: audits for bank items, the fixed map for simulation items.
  const conceptToObjective = {};
  for (const f of fs.readdirSync(path.join(ROOT, "audits")).filter(f => /^ccar-p-d\d\.json$/.test(f))) {
    Object.assign(conceptToObjective, JSON.parse(fs.readFileSync(path.join(ROOT, "audits", f), "utf8")).conceptToObjective);
  }
  const bank = window.CLAUDE_CERT_BANK_EXPANSIONS["ccar-p"].questions;
  const reusedObjectives = {};
  for (const it of items) {
    if (it.objectiveId) continue;
    const src = it.sourceQuestionId;
    let obj = null;
    if (/^P-P\d+-\d+-B$/.test(src)) obj = conceptToObjective[src.match(/^P-(P\d+-\d+)-B$/)[1]];
    else if (/^EXT-/.test(src)) obj = bank.find(q => q.id === src)?.objectiveIds?.[0];
    else if (SIM_OBJECTIVES[src]) obj = SIM_OBJECTIVES[src];
    if (!obj) fail(`No objective for ${it.id}`);
    it.objectiveId = obj; reusedObjectives[it.id] = obj;
  }

  // Pool geometry must equal exactly what six papers need.
  const kind = (it) => it.itemType === "matching" || it.itemType === "matrix" ? "comp" : it.itemType;
  for (const [d, meta] of Object.entries(profile.domains)) {
    const [s, m, c] = TYPE_SPLIT[d];
    if (s + m + c !== meta.mock) fail(`${d}: type split ${s}+${m}+${c} does not equal ${meta.mock}`);
    const pool = items.filter(it => it.domain === d);
    const have = { single: 0, multi: 0, comp: 0 };
    pool.forEach(it => have[kind(it)]++);
    const need = { single: s * PAPER_COUNT, multi: m * PAPER_COUNT, comp: c * PAPER_COUNT };
    for (const k of Object.keys(need)) if (have[k] !== need[k]) fail(`${d}: pool has ${have[k]} ${k}, six papers need ${need[k]}`);
    for (const o of objectivesByDomain[d]) {
      const n = pool.filter(it => it.objectiveId === o).length;
      if (n < PAPER_COUNT) fail(`${o}: only ${n} items, six papers need at least ${PAPER_COUNT}`);
    }
  }

  // One yes/no grid per paper: give each matrix item a different paper.
  const matrices = items.filter(it => it.itemType === "matrix").sort((a, b) => a.id < b.id ? -1 : 1);
  if (matrices.length !== PAPER_COUNT) fail(`Expected ${PAPER_COUNT} matrix items, found ${matrices.length}`);
  const matrixPaper = {};
  builder.shuffle([...Array(PAPER_COUNT).keys()], builder.rng(LAYOUT_VERSION + ":matrix")).forEach((p, i) => { matrixPaper[matrices[i].id] = p; });

  const papers = [...Array(PAPER_COUNT)].map(() => []);
  for (const d of Object.keys(profile.domains)) {
    const [s, m, c] = TYPE_SPLIT[d];
    const pool = items.filter(it => it.domain === d);
    const objectives = objectivesByDomain[d];
    let solved = null;
    for (let attempt = 0; attempt < 5000 && !solved; attempt++) solved = assignDomain(pool, objectives, { single: s, multi: m, comp: c }, matrixPaper, builder.rng(`${LAYOUT_VERSION}:${d}:${attempt}`), builder.shuffle, kind);
    if (!solved) fail(`${d}: no assignment found that satisfies every constraint`);
    solved.forEach((ids, p) => papers[p].push(...ids));
  }

  const layout = {
    version: LAYOUT_VERSION,
    builderVersion: builder.VERSION,
    guideVersion: "Exam Guide v1.0 (effective July 2026)",
    generatedBy: "ccar-f/tools/build-ccar-p-papers.js",
    paperCount: PAPER_COUNT,
    typeSplit: TYPE_SPLIT,
    reusedObjectives,
    papers: papers.map((ids, p) => ({
      id: `paper-${p + 1}`,
      title: `Practice exam ${p + 1}`,
      ids: builder.shuffle(ids.sort(), builder.rng(`${LAYOUT_VERSION}:order:${p}`)),
    })),
  };
  const out = path.join(ROOT, "ccar-p.mock-papers-layout.js");
  const text = "// Generated by ccar-f/tools/build-ccar-p-papers.js. Do not edit by hand; re-run the script instead.\n" +
    `window.CCARP_MOCK_PAPER_LAYOUT = ${JSON.stringify(layout, null, 1)};\n`;
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
    if (current !== text) fail("ccar-p.mock-papers-layout.js is out of date: run node ccar-f/tools/build-ccar-p-papers.js and commit the result");
    console.log("Paper layout is up to date.");
    return;
  }
  fs.writeFileSync(out, text);
  console.log(`Wrote ${path.relative(process.cwd(), out)}: ${PAPER_COUNT} papers x ${layout.papers[0].ids.length} items from ${items.length} pool items.`);
}

// Assign one domain's items to the six papers. Returns six ID lists, or null if this attempt fails.
function assignDomain(pool, objectives, quota, matrixPaper, r, shuffle, kind) {
  const left = new Set(pool.map(it => it.id));
  const byId = Object.fromEntries(pool.map(it => [it.id, it]));
  const out = [...Array(6)].map(() => []);
  const fam = [...Array(6)].map(() => new Set());
  const take = (p, it) => { out[p].push(it.id); fam[p].add(it.family); left.delete(it.id); };
  // Matrices first: they are pinned to their papers.
  for (const it of pool) if (it.itemType === "matrix") take(matrixPaper[it.id], it);
  const quotaOf = (p) => {
    const used = { single: 0, multi: 0, comp: 0 };
    out[p].forEach(id => used[kind(byId[id])]++);
    return { single: quota.single - used.single, multi: quota.multi - used.multi, comp: quota.comp - used.comp };
  };
  // A paper holding this domain's matrix has already used its composite slot, so quotas alone
  // keep matching items out of it.
  const canTake = (p, it) => quotaOf(p)[kind(it)] > 0 && !fam[p].has(it.family);
  // Coverage: every paper gets at least one item for every objective, scarcest objectives first.
  const scarcity = (o) => pool.filter(it => it.objectiveId === o).length;
  for (const p of shuffle([...Array(6).keys()], r)) {
    for (const o of [...objectives].sort((a, b) => scarcity(a) - scarcity(b) || (r() - 0.5))) {
      if (out[p].some(id => byId[id].objectiveId === o)) continue;
      const options = shuffle([...left].map(id => byId[id]).filter(it => it.objectiveId === o && canTake(p, it)), r);
      if (!options.length) return null;
      take(p, options[0]);
    }
  }
  // Fill remaining quotas, spreading objectives as evenly as possible within each paper.
  for (const p of shuffle([...Array(6).keys()], r)) {
    for (const k of ["comp", "multi", "single"]) {
      while (quotaOf(p)[k] > 0) {
        const count = (o) => out[p].filter(id => byId[id].objectiveId === o).length;
        const options = shuffle([...left].map(id => byId[id]).filter(it => kind(it) === k && canTake(p, it)), r).sort((a, b) => count(a.objectiveId) - count(b.objectiveId));
        if (!options.length) return null;
        take(p, options[0]);
      }
    }
  }
  return left.size === 0 ? out : null;
}

main();
